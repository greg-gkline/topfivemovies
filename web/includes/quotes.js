var used = new Array();
prevNode = null;

function numberorder(a, b) { return a - b; }

function getRandom() {
	randNum = Math.round(Math.random()*(q.length-1));
	for ( i = 0; i < randNum && i < used.length; i++ ) {
		if ( randNum == used[i] ) {
			randNum = getRandom();
		}
	}	
	return randNum;
}

function updateQuote() {
	if (document.getElementById ) {
		if ( used.length >= q.length )
			used = new Array();
	
		randNum = getRandom();
				
		quoteText = document.createTextNode(q[randNum]);
		quoteNode = document.getElementById('quote');
		/*quoteNode.addEventListener("click", updateQuote, false);*/

		if ( prevNode != null )		
			quoteNode.removeChild(prevNode);
		quoteNode.appendChild(quoteText);
		prevNode = quoteText;
		
		used.push(randNum);
		used.sort(numberorder);
	
		// repeat every 20 seconds
		setTimeout("updateQuote()", 20 * 1000);	
	}
}

function removeChildNodes(parentNode) {
	kids = parentNode.childNodes;
	for ( i = 0; i < kids.length; i++ )
		parentNode.removeChild(kids[i]);
}
